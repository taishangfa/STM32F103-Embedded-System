/* =============================== GRAM 显存 =============================== */
static uint8_t s_gram[SSD1306_PAGES][SSD1306_WIDTH];

/* ============================== 底层 I2C 通信 ============================== */
/* 发送命令：控制字节0x00 表示后面是命令 */
static void OLED_WriteCmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00U, cmd};
    HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR, buf, 2U, 100U);
}

/* 设置写入位置：page=页地址，x=列地址 */
static void OLED_SetPos(uint8_t x, uint8_t page)
{
    OLED_WriteCmd((uint8_t)(0xB0U + page));                 /* 页地址命令 */
    OLED_WriteCmd((uint8_t)(0x10U | ((x & 0xF0U) >> 4)));  /* 列地址高4位 */
    OLED_WriteCmd((uint8_t)(0x00U | (x & 0x0FU)));         /* 列地址低4位 */
}

/* ============================== 上层显示接口 ============================== */
void OLED_Clear(void)
{
    memset(s_gram, 0, sizeof(s_gram));
}

void OLED_ShowChar(uint8_t x, uint8_t page, char ch)
{
    uint8_t i;
    uint8_t idx;

    /* 边界保护，避免越界写GRAM */
    if (page >= SSD1306_PAGES || (uint16_t)x + 6U > SSD1306_WIDTH)
    {
        return;
    }

    /* 只支持 0x20~0x7E，其他字符显示为空格 */
    if ((uint8_t)ch < 0x20U || (uint8_t)ch > 0x7EU)
    {
        ch = ' ';
    }
    idx = (uint8_t)ch - 0x20U;

    for (i = 0; i < 6U; i++)
    {
        s_gram[page][x + i] = F6x8[idx][i];
    }
}

void OLED_ShowString(uint8_t x, uint8_t page, const char *str)
{
    while (*str != '\0')
    {
        OLED_ShowChar(x, page, *str);
        x += 6U;
        str++;
    }
}

void OLED_Printf(uint8_t x, uint8_t page, const char *fmt, ...)
{
    char buf[24];   /* 一行最多21个字符，24足够 */
    va_list ap;

    va_start(ap, fmt);
    vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);

    OLED_ShowString(x, page, buf);
}

/* 把整屏GRAM分页批量推送到OLED：
   每页先发控制字节0x40（表示后面都是显示数据），随后连续128字节 */
void OLED_Update(void)
{
    uint8_t page;
    uint8_t buf[SSD1306_WIDTH + 1U];

    buf[0] = 0x40U;
    for (page = 0; page < SSD1306_PAGES; page++)
    {
        OLED_SetPos(0U, page);
        memcpy(&buf[1], s_gram[page], SSD1306_WIDTH);
        HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR,
                                buf, (uint16_t)sizeof(buf), 200U);
    }
}

/* ============================== 硬件初始化 ============================== */
void OLED_Init(void)
{
    HAL_Delay(100U);          /* 上电等待屏幕稳定 */

    OLED_WriteCmd(0xAEU);     /* 关闭显示 */

    OLED_WriteCmd(0xD5U);     /* 设置显示时钟分频/振荡频率 */
    OLED_WriteCmd(0x80U);

    OLED_WriteCmd(0xA8U);     /* 设置多路复用路数 = 64 */
    OLED_WriteCmd(0x3FU);

    OLED_WriteCmd(0xD3U);     /* 设置显示偏移 = 0 */
    OLED_WriteCmd(0x00U);

    OLED_WriteCmd(0x40U);     /* 显示起始行 = 0 */

    OLED_WriteCmd(0x8DU);     /* 电荷泵设置 */
    OLED_WriteCmd(0x14U);     /* 开启电荷泵（3.3V供电必须） */

    OLED_WriteCmd(0x20U);     /* 内存寻址模式 */
    OLED_WriteCmd(0x02U);     /* 页寻址模式 */

    OLED_WriteCmd(0xA1U);     /* 段重映射：左右方向正常 */
    OLED_WriteCmd(0xC8U);     /* COM扫描方向：上下方向正常 */

    OLED_WriteCmd(0xDAU);     /* COM引脚硬件配置 */
    OLED_WriteCmd(0x12U);

    OLED_WriteCmd(0x81U);     /* 对比度设置 */
    OLED_WriteCmd(0xCFU);

    OLED_WriteCmd(0xD9U);     /* 预充电周期 */
    OLED_WriteCmd(0xF1U);

    OLED_WriteCmd(0xDBU);     /* VCOMH电平 */
    OLED_WriteCmd(0x30U);

    OLED_WriteCmd(0xA4U);     /* 输出跟随GRAM内容 */
    OLED_WriteCmd(0xA6U);     /* 正常显示（非反色） */
    OLED_WriteCmd(0xAFU);     /* 开启显示 */

    OLED_Clear();             /* 清空GRAM */
    OLED_Update();            /* 推送一次黑屏，避免上电花屏 */
}
